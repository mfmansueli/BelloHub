// Generates src/lib/regions.generated.ts from the iOS region presets, so the web and the app share one table
// of calling codes, national number lengths and trunk prefixes (docs/16-MARKETS.md section 1).
//
// The output is git-ignored and rebuilt by `npm run gen`, which every other npm script runs first.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../BelloHub/Resources/Regions/regions.json');
const target = resolve(here, '../src/lib/regions.generated.ts');

interface RawRegion {
  code: string;
  callingCode: string;
  defaultCurrency: string;
  defaultLocalization: string;
  localizations: string[];
  nationalLengths: number[];
  trunkPrefix?: string;
  timeZones: string[];
  wave: number;
}

const raw = JSON.parse(readFileSync(source, 'utf8')) as RawRegion[];

const lines = raw.map((region) => {
  const trunk = region.trunkPrefix === undefined ? '' : `, trunkPrefix: '${region.trunkPrefix}'`;
  return (
    `  { code: '${region.code}', callingCode: '${region.callingCode}', ` +
    `nationalLengths: [${region.nationalLengths.join(', ')}]${trunk}, currency: '${region.defaultCurrency}', ` +
    `localization: '${region.defaultLocalization}', timeZone: '${region.timeZones[0] ?? ''}' },`
  );
});

const output = `// Generated by scripts/gen-regions.ts from BelloHub/Resources/Regions/regions.json. Do not edit.

export interface RegionPreset {
  readonly code: string;
  readonly callingCode: string;
  readonly nationalLengths: readonly number[];
  readonly trunkPrefix?: string;
  readonly currency: string;
  readonly localization: string;
  readonly timeZone: string;
}

export const REGION_PRESETS: readonly RegionPreset[] = [
${lines.join('\n')}
];
`;

writeFileSync(target, output);

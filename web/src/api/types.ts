// The contract between the page and the Cloud Functions: firebase/functions/API.md (contract v1), sections 4 and 5.
//
// Two layers live here. The "wire" types are exactly what API.md sends and receives (callable functions, see
// transport.ts). The "page" types below them are what the screens render: the same data, plus a few derived fields
// (the first name, the rules split into lines, the professional's full public profile beside a booking) that
// `parse.ts` computes once so no screen repeats it. Nothing in these types is clinical: a health answer never has
// a field.

import type { LocaleId, LocalizedText } from '../lib/locales';
import type { PolicyValues } from '../lib/policy';

// MARK: - Wire: shared shapes (API.md section 4)

/** The professional's inbox public key (docs/06 section 3.2). `pub` is 32 bytes, base64url. */
export interface InboxKey {
  readonly keyId: string;
  readonly alg: 'hpke-v1';
  readonly pub: string;
}

export type PriceDisplay = 'show' | 'startingFrom' | 'onRequest';

/** A price is information only (no payment exists anywhere in the product). Absent = not shown. */
export interface Money {
  readonly display: PriceDisplay;
  readonly amount?: number;
}

export interface PublicService {
  readonly id: string;
  readonly name: string;
  readonly category?: string;
  readonly durationMinutes: number;
  readonly price?: Money;
}

export interface PublicAddOn {
  readonly id: string;
  readonly name: string;
  readonly minutes: number;
  /** Free text ("+ R$ 20"); never summed. */
  readonly priceText?: string;
}

export interface PublicCredential {
  readonly title: string;
  readonly institution?: string;
  readonly year?: number;
  readonly registrationNumber?: string;
}

export interface BookingSettings {
  readonly acceptingBookings: boolean;
  readonly pausedUntil?: string;
  readonly requiresApproval: boolean;
  readonly maxGuests: 0 | 1 | 2;
  readonly maxDaysAhead: number;
}

/** `PublicProfile` of API.md section 4, as published by her app. */
export interface WireProfile {
  readonly schemaVersion: 1;
  readonly slug: string;
  readonly displayName: string;
  readonly businessName?: string;
  readonly bio?: string;
  readonly city?: string;
  readonly regionCode: string;
  readonly photo?: string;
  readonly timeZoneID: string;
  readonly currencyCode: string;
  /** Booking page languages, the first is the default. */
  readonly locales: readonly LocaleId[];
  readonly whatsappE164?: string;
  readonly credentials: readonly PublicCredential[];
  readonly services: readonly PublicService[];
  readonly addOns: readonly PublicAddOn[];
  readonly booking: BookingSettings;
  readonly policy: PolicyValues;
  /** One text per booking language, generated by her app from `policy`; shown as published. */
  readonly rulesText: Readonly<Partial<Record<string, string>>>;
  readonly legalNotice?: string;
  readonly inboxKey: InboxKey;
  readonly updatedAt: string;
}

export interface PublicPageResponse {
  readonly profile: WireProfile;
  readonly intakeAvailable: boolean;
  readonly features: { readonly whatsAppAutomation: boolean; readonly smsCallingCodes: readonly string[] };
  readonly serverTime: string;
}

// MARK: - Wire: requests and responses (API.md section 5)

/** 5.2 `getSlots`. `from`/`to` are calendar days in the business zone, at most 42 days apart. */
export interface SlotQuery {
  readonly slug: string;
  readonly serviceId: string;
  readonly addOnIds?: readonly string[];
  readonly guests?: number;
  readonly from: string;
  readonly to: string;
  /** Your own hold does not block you. */
  readonly holdKey?: string;
  /** Moving an existing booking: its own time does not block it, and its service, add-ons and guests are used. */
  readonly rescheduleToken?: string;
}

export interface WireSlotsResponse {
  readonly timeZoneID: string;
  readonly durationMinutes: number;
  readonly paused: boolean;
  readonly days: readonly { readonly date: string; readonly slots: readonly string[] }[];
}

/** 5.3 `holdSlot`. `holdKey` is 16 to 64 random characters made by the browser; a new hold replaces the previous one. */
export interface HoldRequest {
  readonly slug: string;
  readonly serviceId: string;
  readonly addOnIds?: readonly string[];
  readonly guests?: number;
  readonly startsAt: string;
  readonly holdKey: string;
}

export type WireHoldResponse =
  | { readonly status: 'held'; readonly holdId: string; readonly expiresAt: string }
  | { readonly status: 'slotTaken'; readonly alternatives: readonly string[] }
  | { readonly status: 'paused' };

/**
 * 5.6 and 5.8: how the client proved she holds the email (a single-use proof). D46: the page verifies by e-mail code
 * only; the `phone` method of API.md 5.7 needs the Firebase JS SDK and reCAPTCHA, which the strict CSP forbids.
 */
export interface VerificationProof {
  readonly method: 'email';
  readonly proof: string;
}

export interface SendEmailCodeRequest {
  readonly slug: string;
  readonly email: string;
  readonly locale: LocaleId;
  readonly purpose: 'booking' | 'find';
}

export interface SendCodeResponse {
  readonly resendAfterSeconds: number;
  readonly expiresInSeconds?: number;
}

/** 5.8 `createBooking`. Only `note` travels from the first-visit screen (<= 300 chars, never clinical). */
export interface CreateBookingRequest {
  readonly slug: string;
  readonly serviceId: string;
  readonly addOnIds?: readonly string[];
  readonly guests?: number;
  readonly startsAt: string;
  readonly client: {
    readonly name: string;
    readonly phone: string;
    readonly email?: string;
    readonly locale: LocaleId;
  };
  readonly note?: string;
  readonly verification: VerificationProof;
  /** New for each attempt the user starts; reused only to retry the SAME request. */
  readonly idempotencyKey: string;
  /** Converts your hold. */
  readonly holdKey?: string;
}

export interface BookedResult {
  readonly status: 'confirmed' | 'pendingApproval';
  readonly bookingId: string;
  readonly manageToken: string;
  readonly startsAt: string;
  readonly endsAt: string;
  readonly timeZoneID: string;
  readonly serviceName: string;
  readonly emailSent: boolean;
}

/** What `createBooking` and `rebook` answer. The page never learns why a booking waits for approval (D42). */
export type BookingOutcome =
  | BookedResult
  | { readonly status: 'slotTaken'; readonly alternatives: readonly string[] }
  | { readonly status: 'paused'; readonly pausedUntil?: string };

/** 5.9 `findBookings`. */
export interface FindBookingsRequest {
  readonly slug: string;
  readonly phone?: string;
  readonly email?: string;
  readonly verification: VerificationProof;
}

export interface FoundBooking {
  readonly bookingId: string;
  /** A fresh personal link token, issued by the server for this lookup. */
  readonly manageToken: string;
  readonly serviceName: string;
  readonly startsAt: string;
  readonly endsAt: string;
  readonly timeZoneID: string;
  readonly status: 'confirmed' | 'pendingApproval';
}

/** 5.10 `joinWaitlist`. Days are calendar dates in the business zone. */
export interface WaitlistRequest {
  readonly slug: string;
  readonly serviceId?: string;
  readonly name: string;
  readonly phone: string;
  readonly locale: LocaleId;
  readonly dayFrom: string;
  readonly dayTo: string;
}

export type BookingStatus = 'confirmed' | 'pendingApproval' | 'cancelledByClient' | 'cancelledByPro' | 'declined' | 'noShow';
export type BookingPhase = 'upcoming' | 'inProgress' | 'past';

/** The server's verdict on what she may do now, from the booking's own policy snapshot and the server clock. */
export interface BookingActions {
  readonly cancel: 'free' | 'allowedWithWarning' | 'askByMessage' | 'unavailable';
  readonly reschedule: 'direct' | 'request' | 'message' | 'unavailable';
  readonly isInsideFreeWindow: boolean;
  readonly hoursUntilStart: number;
  readonly cancellationWouldBeLate: boolean;
  readonly canConfirmPresence: boolean;
  readonly canReportLate: boolean;
}

/** 5.11 `getBooking`. */
export interface WireBooking {
  readonly bookingId: string;
  readonly status: BookingStatus;
  readonly phase: BookingPhase;
  readonly slug: string;
  readonly professional: { readonly displayName: string; readonly businessName?: string; readonly whatsappE164?: string };
  readonly service: { readonly id: string; readonly name: string };
  readonly addOns: readonly { readonly id: string; readonly name: string; readonly minutes: number }[];
  readonly guestCount: number;
  readonly startsAt: string;
  readonly endsAt: string;
  readonly durationMinutes: number;
  readonly timeZoneID: string;
  /** The server clock, so a phone with a wrong clock still shows the right free window. */
  readonly serverTime: string;
  readonly client: { readonly name: string };
  /** The policy as it was when she booked (later edits never change a client's rights). */
  readonly policy: PolicyValues;
  readonly rulesText: Readonly<Partial<Record<string, string>>>;
  readonly actions: BookingActions;
  readonly clientConfirmedAt?: string;
  readonly lateByMinutes?: number;
  readonly rescheduleCount: number;
  readonly pendingReschedule?: { readonly requestedStart: string; readonly status: 'pending' | 'declined' };
  /** First visit, or the last sealed form is older than 12 months. */
  readonly intakeRequired: boolean;
  readonly tokenExpiresAt: string;
}


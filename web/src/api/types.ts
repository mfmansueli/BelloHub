// The contract between the page and the Cloud Functions (docs/11-BACKEND-FIREBASE.md section 3).
//
// The page talks to the server only through `api/client.ts`, which speaks these types. firebase/functions/API.md
// is the other side of the same contract; where they differ the coordinator reconciles them (docs/agent-notes/web.md
// lists every assumption made here). Nothing in these types is clinical: a health answer never has a field.

import type { LocaleId, LocalizedText } from '../lib/locales';
import type { PolicyValues } from '../lib/policy';

// MARK: - Shared

/** The professional's inbox public key (docs/06 section 3.2). `pub` is 32 bytes, base64url. */
export interface InboxKey {
  readonly keyId: string;
  readonly alg: 'hpke-v1';
  readonly pub: string;
}

/** One line of "Maria's rules", generated by her app from her policy and published once per localization. */
export interface RuleLine {
  readonly kind: 'link' | 'changes' | 'reschedule' | 'noShow';
  readonly text: string;
}

export type PriceDisplay = 'show' | 'startingFrom' | 'onRequest' | 'hide';

export interface PublicService {
  readonly id: string;
  readonly name: string;
  readonly durationMinutes: number;
  readonly priceDisplay: PriceDisplay;
  readonly priceAmount?: number;
}

export interface PublicAddOn {
  readonly id: string;
  readonly name: string;
  readonly minutes: number;
  /** Numeric price, summed into the total when the service price is shown. */
  readonly priceAmount?: number;
}

/** Enough about the professional to head any page and open her WhatsApp. */
export interface ProfessionalLite {
  readonly slug: string;
  readonly displayName: string;
  readonly firstName: string;
  /** A small `data:image/...` URI (the page's CSP allows images from itself and `data:` only). */
  readonly photo?: string;
  readonly whatsappE164?: string;
  readonly locales: readonly LocaleId[];
  readonly defaultLocale: LocaleId;
  readonly regionCode: string;
  readonly timeZoneID: string;
  readonly currencyCode: string;
  readonly city?: string;
  /** Her override of the week start (0 = Sunday), published from `LocalePrefs` (D25). Absent: the region decides. */
  readonly weekStart?: number;
  /** Her override of the clock (`LocalePrefs.use24Hour`). Absent: the region decides. */
  readonly use24Hour?: boolean;
}

export interface PublicProfile extends ProfessionalLite {
  readonly headline?: LocalizedText;
  readonly bio?: LocalizedText;
  readonly tags?: readonly string[];
  readonly credentials: {
    readonly verifiedByPro: boolean;
    readonly items: readonly { readonly title: string; readonly institution?: string; readonly year?: number }[];
  };
  readonly services: readonly PublicService[];
  readonly addOns: readonly PublicAddOn[];
  /** Rule lines per localization, in the order they are shown. */
  readonly rules: Readonly<Partial<Record<string, readonly RuleLine[]>>>;
  readonly policy: PolicyValues;
  readonly booking: {
    readonly accepting: boolean;
    /** ISO date she is back, when paused with a return date. */
    readonly pausedUntil?: string;
    readonly confirmNewClients: boolean;
    readonly maxGuests: 0 | 1 | 2;
    readonly maxDaysAhead: number;
    /** Ask the quick first-visit questions (default true). */
    readonly askFirstVisitQuestions?: boolean;
    readonly waitlist: boolean;
  };
  readonly inboxKey: InboxKey;
  readonly channels: {
    /** True once WhatsApp Business automation is on (D31): the copy then promises a WhatsApp confirmation. */
    readonly whatsAppAutomation: boolean;
    /** Email codes are always offered; false only if the server turned them off. */
    readonly emailCode?: boolean;
  };
}

// MARK: - Availability

export type SlotQuery =
  | {
      readonly slug: string;
      readonly serviceId: string;
      readonly addOnIds: readonly string[];
      readonly guests: number;
      readonly from: string;
      readonly to: string;
    }
  | {
      readonly token: string;
      /** `reschedule` frees the booking's own time; `rebook` is a new booking of the same service. */
      readonly purpose: 'reschedule' | 'rebook';
      readonly from: string;
      readonly to: string;
    };

export interface SlotsResponse {
  /** Free start times, UTC ISO strings, ascending. */
  readonly slots: readonly string[];
  /** Total duration the slots were computed for (service, add-ons and guests in sequence, D19). */
  readonly durationMinutes: number;
}

export interface HoldRequest {
  readonly slug: string;
  readonly serviceId: string;
  readonly addOnIds: readonly string[];
  readonly guests: number;
  readonly startsAt: string;
  /** Random per browser tab; the server stores only its hash with the hold. */
  readonly sessionKey: string;
}

export interface HoldResponse {
  readonly holdId: string;
  readonly expiresAt: string;
}

// MARK: - Verification (D31, D37)

export type VerificationProof =
  | { readonly kind: 'sms'; readonly idToken: string }
  | { readonly kind: 'email'; readonly token: string };

export interface SendEmailCodeRequest {
  readonly slug: string;
  readonly email: string;
  readonly locale: LocaleId;
  readonly purpose: 'booking' | 'find';
}

export interface SendCodeResponse {
  readonly resendAfterSeconds: number;
}

// MARK: - Booking

export type HeardFrom = 'friend' | 'instagram' | 'search' | 'passing' | 'other';

/** The quick first-visit questions: non-clinical, the same for every profession. Clinical answers only exist in the sealed form. */
export interface FirstVisitAnswers {
  readonly heardFrom: HeardFrom | null;
  readonly hadBefore: boolean | null;
  /** A short preference note. The page asks her not to write health details here. */
  readonly note: string;
}

export interface CreateBookingRequest {
  readonly slug: string;
  readonly serviceId: string;
  readonly addOnIds: readonly string[];
  readonly guests: readonly { readonly name: string }[];
  readonly startsAt: string;
  readonly holdId?: string;
  readonly client: {
    readonly name: string;
    readonly phone: string;
    readonly email?: string;
    readonly locale: LocaleId;
  };
  readonly firstVisit?: FirstVisitAnswers;
  readonly verification: VerificationProof;
  /** Same key on a retry, so a double tap cannot book twice. */
  readonly idempotencyKey: string;
}

export type BookingStatus =
  | 'confirmed'
  | 'pendingApproval'
  | 'cancelledByClient'
  | 'cancelledByPro'
  | 'declined'
  | 'completed'
  | 'noShow';

export interface BookingView {
  readonly id: string;
  readonly status: BookingStatus;
  readonly service: { readonly id: string; readonly name: string; readonly durationMinutes: number };
  readonly addOns: readonly { readonly id: string; readonly name: string; readonly minutes: number }[];
  readonly guestCount: number;
  readonly guestNames?: readonly string[];
  readonly startsAt: string;
  readonly endsAt: string;
  readonly totalMinutes: number;
  readonly price?: { readonly display: Exclude<PriceDisplay, 'hide'>; readonly amount?: number; readonly currency: string };
  readonly professional: ProfessionalLite;
  /** The first name she booked with, to greet her ("Welcome back, Ana"). Never a surname, never clinical. */
  readonly client?: { readonly firstName: string };
  readonly rules?: Readonly<Partial<Record<string, readonly RuleLine[]>>>;
  /** The policy as it was when she booked (later edits never change a client's rights). */
  readonly policy: PolicyValues;
  readonly rescheduleCount: number;
  readonly clientConfirmedAt?: string;
  readonly lateByMinutes?: number;
  /** What she answered to a running-late message, if she did. */
  readonly proReply?: string;
  readonly rescheduleRequest?: { readonly requestedStart: string };
  /** The time it had before the last reschedule. */
  readonly movedFrom?: string;
  readonly forms: {
    readonly intake: 'pending' | 'done' | 'notNeeded';
    readonly checkIn: 'available' | 'none';
  };
  /** The server clock, so a phone with a wrong clock still shows the right free window. */
  readonly serverNow: string;
}

export type BookingResult =
  | { readonly status: 'confirmed'; readonly manageToken: string; readonly booking: BookingView }
  | {
      readonly status: 'pendingApproval';
      readonly reason: 'newClient' | 'noShowLimit' | 'registrationLimit';
      readonly manageToken?: string;
    }
  | { readonly status: 'paused'; readonly scope: 'page' | 'client'; readonly pausedUntil?: string }
  | { readonly status: 'slotTaken'; readonly nextSlots: readonly string[] };

export interface FoundBooking {
  /** A fresh personal link token, issued by the server for this lookup. */
  readonly manageToken: string;
  readonly serviceName: string;
  readonly startsAt: string;
  readonly endsAt: string;
  readonly totalMinutes: number;
  readonly professionalName: string;
}

export interface WaitlistRequest {
  readonly slug: string;
  readonly serviceId: string;
  readonly name: string;
  readonly phone: string;
  /** Civil dates in the business zone. */
  readonly dateFrom: string;
  readonly dateTo: string;
  readonly locale: LocaleId;
}

// MARK: - Management by token

export interface RescheduleDirect {
  readonly token: string;
  readonly startsAt: string;
  readonly holdId?: string;
}

export interface RescheduleAsk {
  readonly token: string;
  readonly startsAt: string;
  readonly note?: string;
}

export interface CancelRequest {
  readonly token: string;
  readonly reason?: string;
}

export interface CancelResponse {
  readonly booking: BookingView;
  /** The server's verdict: it was a late cancellation that counts as missed. */
  readonly countedAsLate: boolean;
}

export interface LateResponse {
  readonly lateByMinutes: number;
  readonly proReply?: string;
}

export interface RebookRequest {
  /** A manage token or a portal token. */
  readonly token: string;
  readonly startsAt: string;
  readonly holdId?: string;
  readonly note?: string;
}

// MARK: - Portal and forms

export interface PortalView {
  readonly professional: ProfessionalLite;
  readonly client: { readonly firstName: string };
  /** The service she would book again and the date she recommends. */
  readonly next?: {
    readonly serviceId: string;
    readonly serviceName: string;
    readonly durationMinutes: number;
    readonly recommendedDate?: string;
    readonly price?: BookingView['price'];
  };
  readonly past: readonly { readonly date: string; readonly serviceName: string; readonly note?: string }[];
  readonly aftercare: readonly {
    readonly date: string;
    readonly serviceName: string;
    readonly lines: readonly string[];
  }[];
  readonly products: readonly { readonly name: string; readonly note?: string }[];
  readonly forms: { readonly intake: 'pending' | 'done' | 'notNeeded'; readonly checkIn: 'available' | 'none' };
  /** The booking this link belongs to, when there is an upcoming one. */
  readonly upcoming?: { readonly manageToken: string; readonly startsAt: string; readonly serviceName: string };
  readonly rebookMode: 'direct' | 'approval' | 'paused';
}

export type QuestionKind = 'yesNo' | 'choice' | 'multiChoice' | 'text';

export interface FormQuestion {
  readonly key: string;
  readonly kind: QuestionKind;
  readonly label: LocalizedText;
  readonly hint?: LocalizedText;
  readonly required?: boolean;
  readonly options?: readonly { readonly value: string; readonly label: LocalizedText }[];
  /** Shown only for an adult visit or only for a minor's. */
  readonly audience?: 'adult' | 'minor';
}

export interface FormContext {
  readonly professional: ProfessionalLite;
  readonly bookingId: string;
  readonly client: { readonly firstName: string };
  readonly inboxKey: InboxKey;
  readonly intake: {
    readonly available: boolean;
    /** Server flag, no content: an intake was already sealed within the last 12 months. */
    readonly completedWithin12Months: boolean;
    readonly formVersion: string;
    readonly questions: readonly FormQuestion[];
  };
  readonly checkIn: { readonly available: boolean; readonly serviceName?: string };
  /** The date of the last sealed intake the server saw (an operational signal, no content). */
  readonly lastIntakeAt?: string;
}

/** The envelope the server stores (docs/06 section 3.3). */
export interface SealedEnvelope {
  readonly v: 1;
  readonly suite: 'hpke-x25519-hkdf-sha256-chacha20poly1305';
  readonly keyId: string;
  readonly kind: 'intake' | 'checkin' | 'datarequest';
  readonly itemId: string;
  readonly enc: string;
  readonly ct: string;
}

// MARK: - Errors

/** Who to contact when a link is unknown or expired, so the page can say "Message Maria" (docs/10 section 2). */
export interface ErrorContact {
  readonly displayName: string;
  readonly firstName: string;
  readonly whatsappE164?: string;
}


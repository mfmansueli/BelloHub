#!/usr/bin/env bash
# Usage: scripts/fetch-wordlist.sh
# Downloads the official BIP-39 English word list (2048 words), checks it, and writes
# BelloHub/Managers/Vault/Bip39Wordlist.swift. The recovery phrase uses only the mnemonic encode/decode with its
# checksum so a typo is detected (docs/06-PRIVACY-SECURITY.md section 4.1); it is not a wallet.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
URL="https://raw.githubusercontent.com/bitcoin/bips/master/bip-0039/english.txt"
OUT="$ROOT/BelloHub/Managers/Vault/Bip39Wordlist.swift"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

curl --fail --silent --show-error --location --max-time 60 "$URL" --output "$TMP"

count="$(wc -l < "$TMP" | tr -d ' ')"
unique="$(sort -u "$TMP" | wc -l | tr -d ' ')"
first="$(head -1 "$TMP")"
last="$(tail -1 "$TMP")"
if [[ "$count" != 2048 || "$unique" != 2048 || "$first" != "abandon" || "$last" != "zoo" ]]; then
    echo "error: not the BIP-39 English list (lines $count, unique $unique, first '$first', last '$last')" >&2
    exit 1
fi
# Every word is lowercase ASCII letters, 3 to 8 long, and no two words share their first four letters.
if grep -qvE '^[a-z]{3,8}$' "$TMP"; then
    echo "error: a word is not 3 to 8 lowercase letters" >&2
    exit 1
fi
if [[ "$(cut -c1-4 "$TMP" | sort -u | wc -l | tr -d ' ')" != 2048 ]]; then
    echo "error: two words share their first four letters (the list is unique by 4-letter prefix)" >&2
    exit 1
fi

mkdir -p "$(dirname "$OUT")"
{
    echo "//"
    echo "//  Bip39Wordlist.swift"
    echo "//  BelloHub"
    echo "//"
    echo "//  Generated by scripts/fetch-wordlist.sh from the official BIP-39 English list (MIT licensed,"
    echo "//  https://github.com/bitcoin/bips/blob/master/bip-0039/bip-0039-wordlists.md). Do not edit by hand."
    echo "//"
    echo
    echo "/// The 2048 words of the BIP-39 English list, in order. The order is the encoding: never reorder."
    echo "enum Bip39Wordlist {"
    echo "    static let words: [String] = \"\"\""
    cat "$TMP"
    echo "\"\"\".split(separator: \"\\n\").map(String.init)"
    echo "}"
} > "$OUT"

echo "Wrote ${OUT#"$ROOT"/} (2048 words, sha256 $(shasum -a 256 "$TMP" | cut -d' ' -f1))"
